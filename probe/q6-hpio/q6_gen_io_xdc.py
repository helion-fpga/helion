#!/usr/bin/env python3
"""Q6 step 2 input generator: XDC plus Verilog for the HPIO probe.

Reads the step 1 inventory (q6-step1-hpio-inventory.txt) and writes
two files for q6_one_hpio_tile.tcl:

- q6-io-probe.xdc: PACKAGE_PIN plus IOSTANDARD LVCMOS12 for each probe
  port, using the real package pins of the real row-0 HPIO tiles.
- q6-io-probe.v: a q6_io_probe module with one IBUF/OBUF pair per
  probe port, so Vivado keeps the IOBs and places them on the pinned
  sites.

Row 0 means clock-region row 0 (clock region names ending in Y0).
Up to two HPIO tiles are used, two IOBs per tile, matching the two
golden IOBs (IOB_X0Y0 IN, IOB_X0Y1 OUT) per tile. If row 0 has only
one HPIO tile, only one tile is probed and the script says so; if a
chosen IOB site has no package pin in the inventory, the script fails
loud naming the site instead of emitting a constraint it cannot
ground.

Usage:

  python3 q6_gen_io_xdc.py q6-step1-hpio-inventory.txt

Writes q6-io-probe.xdc and q6-io-probe.v in the current directory.

No em dashes anywhere.
"""

import sys


def parse_inventory(path):
    """Parse a q6 step 1 inventory file.

    Returns (part, tiles) where tiles is a list of dicts with keys
    name, tile_type, column, row, clock_region, sites (list of dicts
    with name, site_type, pin).
    """
    part = None
    tiles = []
    by_name = {}
    with open(path) as f:
        for raw in f:
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            fields = line.split()
            if fields[0] == "PART":
                part = fields[1]
            elif fields[0] == "TILE":
                tile = {
                    "name": fields[1],
                    "tile_type": fields[2],
                    "column": int(fields[3]),
                    "row": int(fields[4]),
                    "clock_region": fields[5],
                    "sites": [],
                }
                tiles.append(tile)
                by_name[tile["name"]] = tile
            elif fields[0] == "SITE":
                tile = by_name.get(fields[1])
                if tile is None:
                    raise ValueError("SITE for unknown tile %s" % fields[1])
                tile["sites"].append(
                    {"name": fields[2], "site_type": fields[3], "pin": fields[4]}
                )
    if part is None:
        raise ValueError("inventory has no PART line: %s" % path)
    return part, tiles


def row0_hpio_tiles(tiles):
    """HPIO tiles in clock-region row 0, sorted by tile name."""
    out = []
    for tile in tiles:
        if not tile["tile_type"].startswith("HPIO"):
            continue
        region = tile["clock_region"]
        if region.endswith("Y0"):
            out.append(tile)
    out.sort(key=lambda t: t["name"])
    return out


def iob_sites(tile):
    """IOB sites of a tile (site names starting with IOB_), sorted."""
    sites = [s for s in tile["sites"] if s["name"].startswith("IOB_")]
    sites.sort(key=lambda s: s["name"])
    return sites


def generate(inventory_path):
    part, tiles = parse_inventory(inventory_path)
    row0 = row0_hpio_tiles(tiles)
    if not row0:
        raise ValueError(
            "no HPIO tile in clock-region row 0 for part %s; "
            "step 1 found no row-0 HPIO tile to probe" % part
        )
    if len(row0) > 2:
        print(
            "note: row 0 has %d HPIO tiles, probing the first two: %s"
            % (len(row0), ", ".join(t["name"] for t in row0[:2]))
        )
    chosen = row0[:2]
    ports = []
    for tile in chosen:
        sites = iob_sites(tile)
        if len(sites) < 2:
            raise ValueError(
                "tile %s has only %d IOB sites, need at least 2"
                % (tile["name"], len(sites))
            )
        for site in sites[:2]:
            if site["pin"] == "NONE":
                raise ValueError(
                    "IOB site %s on tile %s has no package pin in the "
                    "inventory; cannot constrain it" % (site["name"], tile["name"])
                )
            ports.append((tile["name"], site["name"], site["pin"]))
    if len(chosen) == 1:
        print(
            "note: row 0 has a single HPIO tile %s; probing it only, "
            "the offset ruling (step 3) cannot be decided from this run"
            % chosen[0]["name"]
        )
    return part, chosen, ports


def write_files(ports, xdc_path="q6-io-probe.xdc", verilog_path="q6-io-probe.v"):
    """Write the XDC and Verilog for the given (tile, site, pin) ports."""
    names = []
    for idx, (_tile, _site, pin) in enumerate(ports):
        direction = "in" if idx % 2 == 0 else "out"
        names.append("%s%d" % (direction, idx // 2))
    with open(xdc_path, "w") as f:
        f.write("# Q6 step 2 constraints, generated by q6_gen_io_xdc.py\n")
        f.write("# One line per probe port; do not hand-edit.\n")
        for name, (_tile, site, pin) in zip(names, ports):
            f.write("# %s on %s\n" % (name, site))
            f.write("set_property PACKAGE_PIN %s [get_ports {%s}]\n" % (pin, name))
            f.write("set_property IOSTANDARD LVCMOS12 [get_ports {%s}]\n" % name)
    pairs = len(ports) // 2
    with open(verilog_path, "w") as f:
        f.write("// Q6 step 2 probe design, generated by q6_gen_io_xdc.py\n")
        f.write("// One IBUF/OBUF pair per row-0 HPIO tile probed.\n")
        f.write("module q6_io_probe(\n")
        decls = []
        for p in range(pairs):
            decls.append("  input wire in%d" % p)
            decls.append("  output wire out%d" % p)
        f.write(",\n".join(decls))
        f.write("\n);\n")
        for p in range(pairs):
            f.write("  wire w%d;\n" % p)
            f.write("  IBUF in_buf%d (.I(in%d), .O(w%d));\n" % (p, p, p))
            f.write("  OBUF out_buf%d (.O(out%d), .I(w%d));\n" % (p, p, p))
        f.write("endmodule\n")
    return names


def main(argv):
    if len(argv) != 2:
        print("usage: python3 q6_gen_io_xdc.py <q6-step1-hpio-inventory.txt>")
        return 2
    part, chosen, ports = generate(argv[1])
    names = write_files(ports)
    print("part: %s" % part)
    for tile in chosen:
        print("probing tile: %s" % tile["name"])
    for name, (tile, site, pin) in zip(names, ports):
        print("port %s: tile %s site %s pin %s" % (name, tile, site, pin))
    print("wrote q6-io-probe.xdc and q6-io-probe.v")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
