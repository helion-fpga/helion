#!/usr/bin/env python3
"""Generate one Verilog variant per row of dsp_variant_table.tsv.

Usage (on the cluster, or anywhere with python3):
    python3 gen_dsp_variants.py [table.tsv] [out_dir]

Each variant is a single DSP48E2 with DONT_TOUCH, all attributes at the
dsp.v defaults except the one override named by the table row. The
baseline (v000) is the dsp.v defaults with no override. Output layout:

    out_dir/v000/dsp_variant.v
    out_dir/v001/dsp_variant.v
    ...
    out_dir/manifest.tsv   (id, attribute, default, variant, verilog)

The generator never edits a variant between runs: the same file is the
input to every Vivado run for that id, so a diff between two runs can
only come from the one attribute that differs.

Defaults are read from the table itself (the `default` column of the
first row for each attribute), so the table is the single source of
truth. The full attribute list with defaults must match the BitFiltrator
dsp.v template; the script aborts if any of the 46 attributes in
EXPECTED_ATTRIBUTES is missing from the table.

No em dashes anywhere.
"""

import sys
from pathlib import Path

EXPECTED_ATTRIBUTES = [
    "AMULTSEL", "A_INPUT", "BMULTSEL", "B_INPUT", "PREADDINSEL", "RND",
    "USE_MULT", "USE_SIMD", "USE_WIDEXOR", "XORSIMD",
    "AUTORESET_PATDET", "AUTORESET_PRIORITY", "MASK", "PATTERN",
    "SEL_MASK", "SEL_PATTERN", "USE_PATTERN_DETECT",
    "IS_ALUMODE_INVERTED", "IS_CARRYIN_INVERTED", "IS_CLK_INVERTED",
    "IS_INMODE_INVERTED", "IS_OPMODE_INVERTED",
    "IS_RSTALLCARRYIN_INVERTED", "IS_RSTALUMODE_INVERTED",
    "IS_RSTA_INVERTED", "IS_RSTB_INVERTED", "IS_RSTCTRL_INVERTED",
    "IS_RSTC_INVERTED", "IS_RSTD_INVERTED", "IS_RSTINMODE_INVERTED",
    "IS_RSTM_INVERTED", "IS_RSTP_INVERTED",
    "ACASCREG", "ADREG", "ALUMODEREG", "AREG", "BCASCREG", "BREG",
    "CARRYINREG", "CARRYINSELREG", "CREG", "DREG", "INMODEREG", "MREG",
    "OPMODEREG", "PREG",
]

# Port connections: identical in every variant. All inputs tied to
# constants, all outputs unconnected, clock tied low. This is the
# dsp.v template wiring with G_SIZE fixed to 1.
PORTS = """        .ACOUT(),
        .BCOUT(),
        .CARRYCASCOUT(),
        .MULTSIGNOUT(),
        .PCOUT(),
        .OVERFLOW(),
        .PATTERNBDETECT(),
        .PATTERNDETECT(),
        .UNDERFLOW(),
        .CARRYOUT(),
        .P(),
        .XOROUT(),
        .ACIN(30'b0),
        .BCIN(18'b0),
        .CARRYCASCIN(1'b0),
        .MULTSIGNIN(1'b0),
        .PCIN(48'b0),
        .ALUMODE(4'b0),
        .CARRYINSEL(3'b0),
        .CLK(1'b0),
        .INMODE(5'b0),
        .OPMODE(9'b0),
        .A(30'b0),
        .B(18'b0),
        .C(48'b0),
        .CARRYIN(1'b0),
        .D(27'b0),
        .CEA1(1'b1),
        .CEA2(1'b1),
        .CEAD(1'b1),
        .CEALUMODE(1'b1),
        .CEB1(1'b1),
        .CEB2(1'b1),
        .CEC(1'b1),
        .CECARRYIN(1'b1),
        .CECTRL(1'b1),
        .CED(1'b1),
        .CEINMODE(1'b1),
        .CEM(1'b1),
        .CEP(1'b1),
        .RSTA(1'b0),
        .RSTALLCARRYIN(1'b0),
        .RSTALUMODE(1'b0),
        .RSTB(1'b0),
        .RSTC(1'b0),
        .RSTCTRL(1'b0),
        .RSTD(1'b0),
        .RSTINMODE(1'b0),
        .RSTM(1'b0),
        .RSTP(1'b0)
"""


def render_value(kind, value):
    """Render a table value as a Verilog literal."""
    if kind == "string":
        return '"%s"' % value
    return value


def render_verilog(run_id, kinds, values, overrides):
    """Render one variant module.

    kinds: attribute -> kind ("string", "int", "bits<N>").
    values: attribute -> default value string.
    overrides: attribute -> variant value string (at most one entry).
    """
    lines = []
    lines.append("// Generated by gen_dsp_variants.py from dsp_variant_table.tsv.")
    lines.append("// Run %s. Do not hand-edit: regenerate from the table." % run_id)
    if overrides:
        for name, value in overrides.items():
            lines.append("// Override: %s = %s (default %s)" % (name, value, values[name]))
    else:
        lines.append("// Baseline: all attributes at dsp.v defaults.")
    lines.append("module dsp_single ();")
    lines.append("")
    lines.append("  (* DONT_TOUCH = \"yes\" *)")
    lines.append("  DSP48E2 #(")
    attr_lines = []
    for name in EXPECTED_ATTRIBUTES:
        value = overrides.get(name, values[name])
        attr_lines.append("    .%s(%s)" % (name, render_value(kinds[name], value)))
    lines.append(",\n".join(attr_lines))
    lines.append("  )")
    lines.append("  DSP48E2_inst (")
    lines.append(PORTS.rstrip("\n"))
    lines.append("  );")
    lines.append("")
    lines.append("endmodule")
    return "\n".join(lines) + "\n"


def read_table(path):
    """Return (kinds, values, variants).

    kinds/values map attribute to kind/default. variants is a list of
    (run_id, attribute, variant_value).
    """
    rows = []
    with open(path, encoding="utf-8") as f:
        header = ""
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            header = line
            break
        assert header.startswith("id\tattribute\tkind\tdefault\tvariant"), header
        for line in f:
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            parts = line.split("\t")
            assert len(parts) == 5, line
            rows.append(parts)
    kinds = {}
    values = {}
    variants = []
    for run_id, attr, kind, default, variant in rows:
        if run_id == "v000":
            continue
        if attr not in kinds:
            kinds[attr] = kind
            values[attr] = default
        else:
            assert kinds[attr] == kind and values[attr] == default, (
                "conflicting default for %s" % attr
            )
        variants.append((run_id, attr, variant))
    missing = [a for a in EXPECTED_ATTRIBUTES if a not in kinds]
    assert not missing, "table is missing attributes: %s" % ", ".join(missing)
    extra = [a for a in kinds if a not in EXPECTED_ATTRIBUTES]
    assert not extra, "table has unknown attributes: %s" % ", ".join(extra)
    return kinds, values, variants


def write_variant(out_dir, run_id, text):
    vdir = out_dir / run_id
    vdir.mkdir(parents=True, exist_ok=True)
    (vdir / "dsp_variant.v").write_text(text, encoding="utf-8")


def main(argv):
    table_path = Path(argv[1]) if len(argv) > 1 else Path("dsp_variant_table.tsv")
    out_dir = Path(argv[2]) if len(argv) > 2 else Path("variants")
    kinds, values, variants = read_table(table_path)
    out_dir.mkdir(parents=True, exist_ok=True)
    manifest = ["id\tattribute\tdefault\tvariant\tverilog"]
    write_variant(out_dir, "v000", render_verilog("v000", kinds, values, {}))
    manifest.append("v000\t-\t-\t-\tv000/dsp_variant.v")
    for run_id, attr, variant in variants:
        write_variant(
            out_dir, run_id,
            render_verilog(run_id, kinds, values, {attr: variant}),
        )
        manifest.append("%s\t%s\t%s\t%s\t%s/dsp_variant.v" % (
            run_id, attr, values[attr], variant, run_id))
    (out_dir / "manifest.tsv").write_text("\n".join(manifest) + "\n", encoding="utf-8")
    print("wrote %d variants + baseline to %s" % (len(variants), out_dir))
    print("manifest: %s" % (out_dir / "manifest.tsv"))


if __name__ == "__main__":
    main(sys.argv)
