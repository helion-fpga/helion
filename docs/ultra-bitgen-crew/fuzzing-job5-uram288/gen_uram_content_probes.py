#!/usr/bin/env python3
"""Generate the job-5 pass-B content probes: one .mem file and one
Verilog wrapper per probe.

Usage (on the cluster, or anywhere with python3):
    python3 gen_uram_content_probes.py [out_dir]

Output layout:

    out_dir/p000/probe.mem
    out_dir/p000/uram_probe.v
    out_dir/p001/probe.mem
    out_dir/p001/uram_probe.v
    ...
    out_dir/manifest.tsv   (id, probe, verilog, mem, mem_sha256)

Why a .mem file and not an attribute: URAM288 has no INIT attributes
in UG974 (see data/URAM288_SEARCH.md section 5), so the BRAM
content-sweep method (vary one INIT word) cannot be copied. The
documented content path is the XPM memory initialization file
(UG974 XPM_MEMORY_SPRAM, 2024.1 English): MEMORY_INIT_FILE names a
.mem file of hex values organized into the specified depth by the
narrowest data width, and IGNORE_INIT_SYNTH 0 means the file applies
for both simulation and synthesis. MEMORY_INIT_PARAM cannot be used
here: the same page states that with MEMORY_INIT_PARAM the maximum
supported memory size is 4K bits, and one URAM288 holds 294,912 bits.

The wrapper instantiates xpm_memory_spram with MEMORY_PRIMITIVE
"ultra", MEMORY_SIZE 294912 (4096 words x 72 bits), ADDR_WIDTH_A 12
(clog2(4096)), READ_DATA_WIDTH_A and WRITE_DATA_WIDTH_A 72,
BYTE_WRITE_WIDTH_A 72 (word-wide writes, so wea is 1 bit),
READ_LATENCY_A 2, ECC_MODE "no_ecc" (ECC and initialization are
mutually exclusive per the same UG974 page: "When ECC is enabled ...
Initialization [is] not supported"), MEMORY_INIT_PARAM "" (the file
is used only when the parameter is empty), and IGNORE_INIT_SYNTH 0.
All parameters and ports are copied from the UG974 XPM_MEMORY_SPRAM
Verilog instantiation template (2024.1), with only the values above
changed. The run script asserts after synthesis that exactly one
URAM288 cell exists, so if synthesis maps the XPM macro elsewhere
the job fails loud on the cluster instead of silently diffing the
wrong cell.

The .mem format follows the same page: ASCII hex values, one per
line, 4096 lines of 18 hex digits (72 bits), line 0 is word 0.
Every probe sets only the words its description names; all other
words are zero. The probes are chosen to learn the mapping
structure, not to sweep all 294,912 bits (that would be 294,912
runs, which is not a job):

    p000  baseline: every word zero.
    p001  word 0, bit 0 = 1 (lowest bit of the lowest word).
    p002  word 0, bit 71 = 1 (highest bit of the lowest word).
    p003  word 0, bit 64 = 1 (first bit past the 64 data bits).
    p004  word 0, all 72 bits = 1 (one full word).
    p005  word 1, bit 0 = 1 (the next word, same bit as p001).
    p006  word 2048, bit 0 = 1 (middle of the array).
    p007  word 4095, bit 71 = 1 (highest bit of the highest word).
    p008  word 4095, all 72 bits = 1 (one full word at the top).
    p009  word 100, bit 35 = 1 (an interior word and bit).
    p010  bit 0 = 1 in every word (one bit per word, 4096 words).
    p011  bit 0 = 1 in words 0..255 (the first 256 words).
    p012  CONTROL: every word all 72 bits = 1. If the p012 .rbt
          equals the p000 .rbt, the init file did not take effect
          and pass B is void: the driver stops and the job reports
          the init mechanism as failed, it does not analyze diffs
          that cannot exist.

No em dashes anywhere.
"""

import hashlib
import sys
from pathlib import Path

WORDS = 4096
BITS = 72
FULL_WORD = (1 << BITS) - 1

# probe id -> {word: value} overrides. Everything else is zero.
PROBES = {
    "p000": {},
    "p001": {0: 0x1},
    "p002": {0: 0x1 << 71},
    "p003": {0: 0x1 << 64},
    "p004": {0: FULL_WORD},
    "p005": {1: 0x1},
    "p006": {2048: 0x1},
    "p007": {4095: 0x1 << 71},
    "p008": {4095: FULL_WORD},
    "p009": {100: 0x1 << 35},
    "p010": {w: 0x1 for w in range(WORDS)},
    "p011": {w: 0x1 for w in range(256)},
    "p012": {w: FULL_WORD for w in range(WORDS)},
}

DESCRIPTIONS = {
    "p000": "baseline all zero",
    "p001": "word 0 bit 0",
    "p002": "word 0 bit 71",
    "p003": "word 0 bit 64",
    "p004": "word 0 all 72 bits",
    "p005": "word 1 bit 0",
    "p006": "word 2048 bit 0",
    "p007": "word 4095 bit 71",
    "p008": "word 4095 all 72 bits",
    "p009": "word 100 bit 35",
    "p010": "bit 0 in every word",
    "p011": "bit 0 in words 0..255",
    "p012": "CONTROL all words all 72 bits",
}

VERILOG_TEMPLATE = """// Generated by gen_uram_content_probes.py. Do not hand-edit.
// Probe {probe_id}: {description}.
// XPM single-port RAM mapped to UltraRAM, initialized from probe.mem.
// Parameters and ports follow the UG974 XPM_MEMORY_SPRAM Verilog
// instantiation template (2024.1); only the values listed here differ.
module uram_content_probe ();

  xpm_memory_spram #(
    .ADDR_WIDTH_A(12),
    .AUTO_SLEEP_TIME(0),
    .BYTE_WRITE_WIDTH_A(72),
    .CASCADE_HEIGHT(0),
    .ECC_MODE("no_ecc"),
    .IGNORE_INIT_SYNTH(0),
    .MEMORY_INIT_FILE("probe.mem"),
    .MEMORY_INIT_PARAM(""),
    .MEMORY_OPTIMIZATION("true"),
    .MEMORY_PRIMITIVE("ultra"),
    .MEMORY_SIZE(294912),
    .READ_DATA_WIDTH_A(72),
    .READ_LATENCY_A(2),
    .READ_RESET_VALUE_A("0"),
    .RST_MODE_A("SYNC"),
    .USE_MEM_INIT(1),
    .WAKEUP_TIME("disable_sleep"),
    .WRITE_DATA_WIDTH_A(72),
    .WRITE_MODE_A("read_first"),
    .WRITE_PROTECT(1)
  ) xpm_memory_spram_inst (
    .dbiterra(),
    .douta(),
    .sbiterra(),
    .addra(12'b0),
    .clka(1'b0),
    .dina(72'b0),
    .ena(1'b1),
    .injectdbiterra(1'b0),
    .injectsbiterra(1'b0),
    .regcea(1'b1),
    .rsta(1'b0),
    .sleep(1'b0),
    .wea(1'b0)
  );

endmodule
"""


def mem_text(overrides):
    """4096 lines of 18 hex digits, line 0 is word 0."""
    lines = []
    for word in range(WORDS):
        lines.append("%018x" % overrides.get(word, 0))
    return "\n".join(lines) + "\n"


def main(argv):
    out_dir = Path(argv[1]) if len(argv) > 1 else Path("probes")
    out_dir.mkdir(parents=True, exist_ok=True)
    manifest = ["id\tprobe\tverilog\tmem\tmem_sha256"]
    for probe_id in sorted(PROBES):
        pdir = out_dir / probe_id
        pdir.mkdir(parents=True, exist_ok=True)
        text = mem_text(PROBES[probe_id])
        (pdir / "probe.mem").write_text(text, encoding="utf-8")
        (pdir / "uram_probe.v").write_text(
            VERILOG_TEMPLATE.format(
                probe_id=probe_id, description=DESCRIPTIONS[probe_id]
            ),
            encoding="utf-8",
        )
        digest = hashlib.sha256(text.encode()).hexdigest()
        manifest.append(
            "%s\t%s\t%s/uram_probe.v\t%s/probe.mem\t%s"
            % (probe_id, DESCRIPTIONS[probe_id], probe_id, probe_id, digest)
        )
    (out_dir / "manifest.tsv").write_text("\n".join(manifest) + "\n", encoding="utf-8")
    print("wrote %d probes to %s" % (len(PROBES), out_dir))
    print("manifest: %s" % (out_dir / "manifest.tsv"))
    print("self-check: every probe.mem is %d lines of 18 hex digits" % WORDS)


if __name__ == "__main__":
    main(sys.argv)
