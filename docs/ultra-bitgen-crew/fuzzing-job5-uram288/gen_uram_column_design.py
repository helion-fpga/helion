#!/usr/bin/env python3
"""Generate the job-5 pass-C column design from column_sites.txt.

Usage:
    python3 gen_uram_column_design.py [sites_file] [out_verilog]

Reads one URAM288 site per line (written by pick_uram_columns.tcl),
and writes a Verilog module with one URAM288 per site, all attributes
at the UG974 defaults, DONT_TOUCH on every cell, all inputs tied to
constants, all outputs unconnected. The instance names are
URAM288_col0, URAM288_col1, ... in site-file order, so
run_uram_column.tcl can place each instance at its site by line
number. The file is generated, never hand-edited: the site list is
the input, and a site list that changes means a different part, not
an edit to this script.

The attribute defaults and port ties are copied from
gen_uram_variants.py (same UG974 source); see that file for the
provenance of every value.

No em dashes anywhere.
"""

