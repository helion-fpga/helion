def main(argv):
    sites_path = Path(argv[1]) if len(argv) > 1 else Path("column_sites.txt")
    out_path = Path(argv[2]) if len(argv) > 2 else Path("column_design.v")
    sites = [l.strip() for l in sites_path.read_text().splitlines() if l.strip()]
    assert sites, "no sites in %s" % sites_path
    assert len(sites) == len(set(sites)), "duplicate sites in %s" % sites_path
    lines = []
    lines.append("// Generated by gen_uram_column_design.py from %s." % sites_path.name)
    lines.append("// One URAM288 per URAM column, all attributes at UG974 defaults.")
    lines.append("// Do not hand-edit: regenerate from the site list.")
    lines.append("module uram_columns ();")
    lines.append("")
    for i, site in enumerate(sites):
        lines.append("  // Column site: %s" % site)
        lines.append('  (* DONT_TOUCH = "yes" *)')
        lines.append("  URAM288 #(")
        attr_lines = ["    .%s(%s)" % (name, value) for name, value in DEFAULTS]
        lines.append(",\n".join(attr_lines))
        lines.append("  )")
        lines.append("  URAM288_col%d (" % i)
        lines.append(PORTS.rstrip("\n"))
        lines.append("  );")
        lines.append("")
    lines.append("endmodule")
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote %d URAM288 instances to %s" % (len(sites), out_path))


if __name__ == "__main__":
    main(sys.argv)
