#!/usr/bin/env python3
"""Generate the H-1 band-code tables for helion-ultrascale.

Reads the two verified formulas from the decoder-validation lane and
writes the checked-in Rust tables module
`crates/helion-ultrascale/src/band_code_tables.rs`.

Sources (read-only inputs, never edited here):
- MAP-A: ~/workspace/ultra-bitgen-crew/decoder-validation/h1_ecc_sparse_maps.json,
  key "A" only. 2,927 entries, string source absolute bit position to
  48-bit column value (u64), constant 0. NEVER use key "B", and never
  use h1_ecc_formula.json or h1_ecc_formula_block0*.json: those are
  poisoned or garbage variants, documented in H1_ECC_TEST.md.
- H76: ~/workspace/ultra-bitgen-crew/decoder-validation/h1_ecc_followup2_formula_h76.json,
  key "formula": per band bit 1440..1487, constant 0, list of source
  absolute bit positions. 20,274 total incidences over 48 band bits.

Free source positions: absolute bits 1502, 1508, 1514, 1520 are
undetermined in the height-76 fit and absent from the H76 source
lists (coefficient 0 there). In MAP-A as saved, only 1502 is absent;
1508, 1514 and 1520 carry nonzero columns determined by the sparse
fit and the single-bit-flip ground truth, so they are kept exactly as
saved. The generator asserts all of this and refuses to emit tables
that do not match the saved files.

Usage:
    python3 crates/helion-ultrascale/tools/gen_band_code.py [--check]
With --check, regenerate to a temp file and diff against the checked-in
tables instead of overwriting them.
"""

import json
import sys
from pathlib import Path

VALIDATION_DIR = Path.home() / "workspace" / "ultra-bitgen-crew" / "decoder-validation"
SPARSE_MAPS = VALIDATION_DIR / "h1_ecc_sparse_maps.json"
H76_FORMULA = VALIDATION_DIR / "h1_ecc_followup2_formula_h76.json"
OUT = Path(__file__).resolve().parent.parent / "src" / "band_code_tables.rs"

BAND_LO = 1440
BAND_HI = 1487
FREE_BITS = (1502, 1508, 1514, 1520)
EXPECTED_MAP_A_ENTRIES = 2927
EXPECTED_H76_INCIDENCES = 20274


def load_map_a():
    with open(SPARSE_MAPS, encoding="utf-8") as f:
        data = json.load(f)
    assert data["constA"] == 0, "MAP-A constant must be 0"
    raw = data["A"]
    assert len(raw) == EXPECTED_MAP_A_ENTRIES, (
        f"MAP-A entries: expected {EXPECTED_MAP_A_ENTRIES}, got {len(raw)}"
    )
    entries = sorted((int(k), int(v)) for k, v in raw.items())
    values = [v for _, v in entries]
    assert all(v != 0 for v in values), "MAP-A columns must all be nonzero"
    assert len(set(values)) == len(values), "MAP-A columns must all be distinct"
    assert all(not (BAND_LO <= s <= BAND_HI) for s, _ in entries), (
        "MAP-A must not list band bits as sources"
    )
    assert 1502 not in dict(entries), "MAP-A must not list free bit 1502"
    return entries


def load_h76():
    with open(H76_FORMULA, encoding="utf-8") as f:
        data = json.load(f)
    formula = data["formula"]
    assert sorted(int(k) for k in formula) == list(range(BAND_LO, BAND_HI + 1)), (
        "H76 must cover exactly band bits 1440..1487"
    )
    offsets = [0]
    sources = []
    for band_bit in range(BAND_LO, BAND_HI + 1):
        entry = formula[str(band_bit)]
        assert entry["constant"] == 0, f"H76 constant for {band_bit} must be 0"
        srcs = sorted(int(s) for s in entry["sources"])
        assert all(not (BAND_LO <= s <= BAND_HI) for s in srcs), (
            f"H76 band bit {band_bit} must not list band bits as sources"
        )
        assert all(s not in FREE_BITS for s in srcs), (
            f"H76 band bit {band_bit} must not list a free bit as a source"
        )
        sources.extend(srcs)
        offsets.append(len(sources))
    assert len(sources) == EXPECTED_H76_INCIDENCES, (
        f"H76 incidences: expected {EXPECTED_H76_INCIDENCES}, got {len(sources)}"
    )
    return offsets, sources


def chunked(items, per_line):
    for i in range(0, len(items), per_line):
        yield items[i : i + per_line]


def render(entries, offsets, sources):
    lines = []
    lines.append("// Generated by tools/gen_band_code.py from the verified H-1 formulas.")
    lines.append("// Do not edit by hand. Re-run the generator to regenerate.")
    lines.append("//")
    lines.append("// Sources:")
    lines.append("// - MAP-A: ultra-bitgen-crew/decoder-validation/h1_ecc_sparse_maps.json,")
    lines.append("//   key \"A\" only. 2,927 entries, constant 0. Never cite key \"B\",")
    lines.append("//   h1_ecc_formula.json, or h1_ecc_formula_block0*.json: poisoned or")
    lines.append("//   garbage variants, see H1_ECC_TEST.md in the same directory.")
    lines.append("// - H76: ultra-bitgen-crew/decoder-validation/h1_ecc_followup2_formula_h76.json,")
    lines.append("//   key \"formula\". 48 band bits, constants 0, 20,274 source incidences.")
    lines.append("//")
    lines.append("// Free source positions 1502, 1508, 1514, 1520 are undetermined in the")
    lines.append("// height-76 fit and absent from the H76 lists. In MAP-A as saved, only")
    lines.append("// 1502 is absent; 1508, 1514 and 1520 carry the nonzero columns the")
    lines.append("// sparse fit determined, kept exactly as saved.")
    lines.append("")
    lines.append("/// MAP-A: (source absolute bit, 48-bit column value), sorted by source.")
    lines.append("/// 2,927 entries. No band bit (1440..1487) is a source; bit 1502 is absent")
    lines.append("/// (coefficient 0). See `band_code.rs` for the proof reference.")
    lines.append("pub static MAP_A: &[(u16, u64)] = &[")
    for group in chunked(entries, 4):
        lines.append(
            "    " + ", ".join(f"({s}, 0x{v:012x})" for s, v in group) + ","
        )
    lines.append("];")
    lines.append("")
    lines.append("/// H76: start offset of each band bit's source list in `H76_SOURCES`.")
    lines.append("/// Index j covers band bit 1440 + j; entry 48 is the end sentinel.")
    lines.append("pub static H76_OFFSETS: &[u32; 49] = &[")
    for group in chunked(offsets, 8):
        lines.append("    " + ", ".join(str(o) for o in group) + ",")
    lines.append("];")
    lines.append("")
    lines.append("/// H76: flat source absolute-bit lists, 20,274 entries in band-bit order.")
    lines.append("pub static H76_SOURCES: &[u16] = &[")
    for group in chunked(sources, 16):
        lines.append("    " + ", ".join(str(s) for s in group) + ",")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def main(argv):
    check = "--check" in argv
    entries = load_map_a()
    offsets, sources = load_h76()
    text = render(entries, offsets, sources)
    if check:
        current = OUT.read_text(encoding="utf-8")
        if current != text:
            print(f"tables differ from checked-in {OUT}", file=sys.stderr)
            return 1
        print(f"tables match checked-in {OUT}")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(entries)} MAP-A entries, {len(sources)} H76 sources)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
