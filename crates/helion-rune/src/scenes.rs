/// Catalog entry for `name`, if it exists.
pub fn expect(name: &str) -> Option<&'static SceneExpect> {
    ALL.iter().find(|e| e.name == name)
}

/// Fresh demo state with the `name`d scene applied, or `None` for an
/// unknown scene name.
pub fn state_for(name: &str) -> Option<AppState> {
    let (_, apply) = crate::SCENES.iter().find(|(n, _)| *n == name)?;
    let mut s = crate::init();
    apply(&mut s);
    Some(s)
}

/// Scene names from the spec, in order. The harness test asserts this
/// matches the catalog so `--scene` coverage never drifts.
pub fn spec_names() -> Vec<&'static str> {
    crate::SCENES.iter().map(|(n, _)| *n).collect()
}

