//! Headless scene catalog for the harness: per-surface `--snap/--tree`
//! scenes plus the keyed regions each one must render.
//!
//! The scene functions themselves live in [`crate::SCENES`] (one entry per
//! surface state, applied with `--scene NAME`; flags from
//! `rune/crates/rune/src/tooling.rs`). This module is the catalog over them:
//! which surface a scene covers, which keys `tests/snap.rs` expects, and
//! helpers to build the pre-scene state. The catalog-vs-spec consistency
//! test fails on drift, so the two lists cannot silently diverge.
//!
//! Rune API citations (rev `a7f276c3630f85a06a0230295da4d2bd172d8d3b`):
//! - `crates/rune/src/tooling.rs`: `AppSpec::scenes`, `--snap/--tree/--scene`.
//! - `examples/hello/src/main.rs`: `Runtime::new` + `find` tap pattern.

use crate::state::AppState;

/// One headless scene's contract: the surface it covers, keys that must be
/// in the tree after the first frame, and keys that must NOT be there.
pub struct SceneExpect {
    /// Scene name, exactly as in [`crate::SCENES`].
    pub name: &'static str,
    /// Which view batch owns the surface (`chrome`, `sources`, ...).
    pub surface: &'static str,
    /// Keys `Runtime::find` must resolve after applying the scene.
    pub keys: &'static [&'static str],
    /// Keys that must be absent (unmounted overlays, other tab bodies, ...).
    pub absent: &'static [&'static str],
}

