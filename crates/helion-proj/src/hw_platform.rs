//! Helion hardware platform hand-off (`write_hw_platform`), the Helion
//! counterpart of a Vivado `.xsa`: one store-only ZIP that software tooling
//! (BSP generators, boot loaders, drivers) consumes without the IDE.
//!
//! # Archive layout
//!
//! ```text
//! platform.json            manifest (below)
//! hw/<top>.bit             bitstream, when one was written
//! hw/bd/<file>             block-design HDL (emitted top + IP RTL)
//! hw/constrs/<file>        board / pin constraints
//! sw/helion_platform.h     C header: base/high addresses per peripheral
//! ```
//!
//! # `platform.json` (format `helion-hw-platform`, version 1)
//!
//! ```json
//! {
//!   "format": "helion-hw-platform",
//!   "version": 1,
//!   "name": "design_1",
//!   "top": "design_1",
//!   "part": "HL10T-C32-1",
//!   "family": "Helion",
//!   "board": "HB1" | null,
//!   "bitstream": { "file": "hw/design_1.bit", "bytes": 1234, "sha256": "…" } | null,
//!   "processor": { "cell": "h_rv32_hb1_0", "vlnv": "…", "reset_vector": "0x00000000",
//!                  "params": { "ENABLE_MUL": "1" } } | null,
//!   "address_map": [
//!     { "cell": "h_uart_0", "vlnv": "community:helion:h_uart:1.0",
//!       "interface": "s_mm", "base": "0x40000000", "high": "0x40000fff", "range": 4096 }
//!   ],
//!   "files": [ { "path": "hw/bd/design_1.sv", "role": "bd-top", "bytes": 2048, "sha256": "…" } ]
//! }
//! ```
//!
//! Addresses are hex strings (JSON numbers lose precision past 2^53); `range`
//! is a byte count. `role` is one of `bitstream`, `bd-top`, `ip-rtl`,
//! `constraints`, `bsp-header`. Consumers must ignore unknown keys; a format
//! change that breaks readers bumps `version`.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use crate::ip_packager::ooc_sha256_hex;
use crate::zip::ZipWriter;

/// Manifest format id.
pub const HW_PLATFORM_FORMAT: &str = "helion-hw-platform";
/// Manifest version.
pub const HW_PLATFORM_VERSION: u32 = 1;

/// One memory-mapped peripheral of the platform.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct HwSegment {
    pub cell: String,
    pub vlnv: String,
    pub interface: String,
    pub base: u64,
    pub range: u64,
}

/// The platform's bus master (processor), when the design has one.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct HwProcessor {
    pub cell: String,
    pub vlnv: String,
    pub reset_vector: u64,
    pub params: BTreeMap<String, String>,
}

/// Everything a hardware platform hand-off describes.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct HwPlatform {
    pub name: String,
    pub top: String,
    pub part: String,
    pub family: String,
    pub board: Option<String>,
    pub bitstream: Option<PathBuf>,
    pub processor: Option<HwProcessor>,
    pub address_map: Vec<HwSegment>,
    /// Emitted block-design top (first) and the IP RTL it instantiates.
    pub bd_sources: Vec<PathBuf>,
    pub constraints: Vec<PathBuf>,
}

/// What [`write_hw_platform`] wrote.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct HwPlatformReport {
    pub path: PathBuf,
    pub bytes: u64,
    pub files: usize,
    pub has_bitstream: bool,
    pub manifest: String,
}

fn json_str(s: &str) -> String {
    let mut o = String::with_capacity(s.len() + 2);
    o.push('"');
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            '\r' => o.push_str("\\r"),
            '\t' => o.push_str("\\t"),
            c if (c as u32) < 0x20 => o.push_str(&format!("\\u{:04x}", c as u32)),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

fn hex(v: u64) -> String {
    json_str(&format!("{v:#010x}"))
}

fn c_ident(s: &str) -> String {
    s.chars()
        .map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_uppercase() } else { '_' })
        .collect()
}

/// Render the C BSP header for the address map.
pub fn platform_header(p: &HwPlatform) -> String {
    let guard = format!("HELION_PLATFORM_{}_H", c_ident(&p.name));
    let mut h = format!(
        "/* Helion hardware platform {} ({}) — generated by write_hw_platform. */\n#ifndef {guard}\n#define {guard}\n\n",
        p.name, p.part
    );
    if let Some(cpu) = &p.processor {
        h.push_str(&format!(
            "#define HELION_CPU_RESET_VECTOR {:#010x}UL /* {} */\n\n",
            cpu.reset_vector, cpu.cell
        ));
    }
    for s in &p.address_map {
        let id = c_ident(&s.cell);
        h.push_str(&format!("#define {id}_BASEADDR {:#010x}UL\n", s.base));
        h.push_str(&format!("#define {id}_HIGHADDR {:#010x}UL\n", s.base + s.range - 1));
    }
    h.push_str(&format!("\n#endif /* {guard} */\n"));
    h
}

/// Write the hand-off archive to `out` (see the module docs for the format).
pub fn write_hw_platform(p: &HwPlatform, out: &Path) -> Result<HwPlatformReport, String> {
    if p.name.is_empty() || p.part.is_empty() {
        return Err("write_hw_platform: name and part are required".into());
    }
    if p.bd_sources.is_empty() && p.bitstream.is_none() {
        return Err("write_hw_platform: nothing to hand off (no block design and no bitstream)".into());
    }
    let mut entries: Vec<(String, &'static str, Vec<u8>)> = Vec::new();
    let mut used = std::collections::BTreeSet::new();
    let mut add = |dir: &str, path: &Path, role: &'static str, entries: &mut Vec<(String, &'static str, Vec<u8>)>| -> Result<String, String> {
        let bytes = std::fs::read(path).map_err(|e| format!("{}: {e}", path.display()))?;
        let base = path.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
        let mut name = format!("{dir}/{base}");
        let mut n = 1;
        while !used.insert(name.clone()) {
            name = format!("{dir}/{n}_{base}");
            n += 1;
        }
        entries.push((name.clone(), role, bytes));
        Ok(name)
    };
    let mut bit_json = "null".to_string();
    if let Some(bit) = &p.bitstream {
        let name = add("hw", bit, "bitstream", &mut entries)?;
        let data = &entries.last().expect("pushed").2;
        bit_json = format!(
            "{{ \"file\": {}, \"bytes\": {}, \"sha256\": {} }}",
            json_str(&name),
            data.len(),
            json_str(&ooc_sha256_hex(data))
        );
    }
    for (i, f) in p.bd_sources.iter().enumerate() {
        add("hw/bd", f, if i == 0 { "bd-top" } else { "ip-rtl" }, &mut entries)?;
    }
    for f in &p.constraints {
        add("hw/constrs", f, "constraints", &mut entries)?;
    }
    entries.push((
        "sw/helion_platform.h".into(),
        "bsp-header",
        platform_header(p).into_bytes(),
    ));
    let proc_json = match &p.processor {
        None => "null".to_string(),
        Some(c) => format!(
            "{{ \"cell\": {}, \"vlnv\": {}, \"reset_vector\": {}, \"params\": {{ {} }} }}",
            json_str(&c.cell),
            json_str(&c.vlnv),
            hex(c.reset_vector),
            c.params
                .iter()
                .map(|(k, v)| format!("{}: {}", json_str(k), json_str(v)))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    };
    let map_json = p
        .address_map
        .iter()
        .map(|s| {
            format!(
                "    {{ \"cell\": {}, \"vlnv\": {}, \"interface\": {}, \"base\": {}, \"high\": {}, \"range\": {} }}",
                json_str(&s.cell),
                json_str(&s.vlnv),
                json_str(&s.interface),
                hex(s.base),
                hex(s.base + s.range - 1),
                s.range
            )
        })
        .collect::<Vec<_>>()
        .join(",\n");
    let files_json = entries
        .iter()
        .map(|(n, role, d)| {
            format!(
                "    {{ \"path\": {}, \"role\": {}, \"bytes\": {}, \"sha256\": {} }}",
                json_str(n),
                json_str(role),
                d.len(),
                json_str(&ooc_sha256_hex(d))
            )
        })
        .collect::<Vec<_>>()
        .join(",\n");
    let manifest = format!(
        "{{\n  \"format\": {},\n  \"version\": {},\n  \"name\": {},\n  \"top\": {},\n  \"part\": {},\n  \"family\": {},\n  \"board\": {},\n  \"bitstream\": {},\n  \"processor\": {},\n  \"address_map\": [\n{}\n  ],\n  \"files\": [\n{}\n  ]\n}}\n",
        json_str(HW_PLATFORM_FORMAT),
        HW_PLATFORM_VERSION,
        json_str(&p.name),
        json_str(&p.top),
        json_str(&p.part),
        json_str(&p.family),
        p.board.as_deref().map(json_str).unwrap_or_else(|| "null".into()),
        bit_json,
        proc_json,
        map_json,
        files_json
    );
    if let Some(parent) = out.parent()
        && !parent.as_os_str().is_empty()
    {
        std::fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
    }
    let f = std::fs::File::create(out).map_err(|e| format!("{}: {e}", out.display()))?;
    let mut z = ZipWriter::new(std::io::BufWriter::new(f));
    z.add("platform.json", manifest.as_bytes())?;
    for (n, _, d) in &entries {
        z.add(n, d)?;
    }
    z.finish()?;
    Ok(HwPlatformReport {
        path: out.to_path_buf(),
        bytes: std::fs::metadata(out).map(|m| m.len()).unwrap_or(0),
        files: entries.len() + 1,
        has_bitstream: p.bitstream.is_some(),
        manifest,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn writes_manifest_files_and_header() {
        let tmp = std::env::temp_dir().join(format!("helion-hwp-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&tmp);
        std::fs::create_dir_all(&tmp).unwrap();
        let top = tmp.join("design_1.sv");
        std::fs::write(&top, "module design_1; endmodule\n").unwrap();
        let bit = tmp.join("design_1.bit");
        std::fs::write(&bit, [0xAAu8, 0x99, 0x55, 0x66]).unwrap();
        let p = HwPlatform {
            name: "design_1".into(),
            top: "design_1".into(),
            part: "HL10T-C32-1".into(),
            family: "Helion".into(),
            board: Some("HB1".into()),
            bitstream: Some(bit),
            processor: Some(HwProcessor {
                cell: "h_rv32_hb1_0".into(),
                vlnv: "community:helion:h_rv32_hb1:1.0".into(),
                reset_vector: 0,
                params: BTreeMap::from([("ENABLE_MUL".into(), "1".into())]),
            }),
            address_map: vec![HwSegment {
                cell: "h_uart_0".into(),
                vlnv: "community:helion:h_uart:1.0".into(),
                interface: "s_mm".into(),
                base: 0x4000_0000,
                range: 0x1000,
            }],
            bd_sources: vec![top],
            constraints: vec![],
        };
        let out = tmp.join("out/design_1.hwp");
        let rep = write_hw_platform(&p, &out).unwrap();
        assert!(rep.has_bitstream);
        let entries = crate::zip::read_zip(&std::fs::read(&out).unwrap()).unwrap();
        let names: Vec<&str> = entries.iter().map(|(n, _)| n.as_str()).collect();
        assert_eq!(names, ["platform.json", "hw/design_1.bit", "hw/bd/design_1.sv", "sw/helion_platform.h"]);
        let m = String::from_utf8(entries[0].1.clone()).unwrap();
        assert!(m.contains("\"format\": \"helion-hw-platform\""));
        assert!(m.contains("\"base\": \"0x40000000\", \"high\": \"0x40000fff\""));
        assert!(m.contains("\"board\": \"HB1\""));
        assert!(m.contains("\"ENABLE_MUL\": \"1\""));
        assert!(m.contains(&ooc_sha256_hex(&[0xAA, 0x99, 0x55, 0x66])));
        let h = String::from_utf8(entries[3].1.clone()).unwrap();
        assert!(h.contains("#define H_UART_0_BASEADDR 0x40000000UL"));
        assert!(write_hw_platform(&HwPlatform { name: "x".into(), part: "p".into(), ..Default::default() }, &out).is_err());
        let _ = std::fs::remove_dir_all(&tmp);
    }
}
