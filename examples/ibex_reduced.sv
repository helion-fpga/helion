// FM-HEL-TOP: reduced Ibex-scale wrap (sha256-style reduce).
// Full examples/ysyx_ibex.sv synths ~6930 cells then TIMEOUT@120s on implement.
// This top keeps hierarchy + scale (N×4-bit counters + XOR tree) but finishes
// helion bitstream under the ≤120s python process-group cap.
// Part: HL10T-C32-1. Pin-reduced (clk + led). No async reset (IMUX-safe).
// Heavy Ibex children (AXI/CSR/multdiv/icache/RF mux) intentionally omitted.

module ibex_cnt4 (
    input  logic clk,
    output logic msb
);
    logic [3:0] cnt;
    always_ff @(posedge clk) begin
        cnt <= cnt + 1;
    end
    assign msb = cnt[3];
endmodule

module ibex_xor4 (
    input  logic a,
    input  logic b,
    input  logic c,
    input  logic d,
    output logic y
);
    assign y = ((a ^ b) ^ (c ^ d));
endmodule

