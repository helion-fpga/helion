#!/usr/bin/env python3
"""
Generate the full 222-class NPN table for 4-input functions.

Enumerates all 65,536 4-input truth tables, classifies each into its NPN
equivalence class using the same algorithm as helion-sv's npn_canonical_4(),
and finds the optimal AIG implementation for each class.

Output: Rust source file with the 222 entries.

This is a long-running script (hours). Run with: python3 gen_npn_table.py > npn_table_full.rs
"""

import itertools

def npn_canonical_4(tt):
    """
    Compute NPN canonical form for 4-input truth table.
    Returns (canonical_tt, in_neg_mask, perm_tuple, out_neg).
    
    This mirrors the Rust implementation in helion-sv/src/lib.rs.
    For the Python script, we use a simplified version that finds
    the minimal truth table under all NPN transformations.
    """
    best = None
    best_transform = None
    
    # All 24 permutations of 4 inputs
    for perm in itertools.permutations(range(4)):
        # All 16 input negation masks
        for in_neg in range(16):
            # Apply permutation and input negations
            transformed = 0
            for m in range(16):
                # Permute inputs: new_m has bit i = old_m bit perm[i]
                # Negate inputs: flip bit i if in_neg has bit i set
                new_m = 0
                for i in range(4):
                    bit = (m >> perm[i]) & 1
                    if (in_neg >> i) & 1:
                        bit ^= 1
                    new_m |= bit << i
                # Copy output bit
                if (tt >> m) & 1:
                    transformed |= 1 << new_m
            
            # Try without output negation
            if best is None or transformed < best:
                best = transformed
                best_transform = (in_neg, perm, False)
            
            # Try with output negation
            inv_transformed = (~transformed) & 0xFFFF
            if inv_transformed < best:
                best = inv_transformed
                best_transform = (in_neg, perm, True)
    
    return best, best_transform

def count_classes():
    """Count NPN classes and find representatives."""
    classes = {}  # canonical_tt -> (count, example_tt)
    
    for tt in range(65536):
        canon, _ = npn_canonical_4(tt)
        if canon not in classes:
            classes[canon] = [0, tt]
        classes[canon][0] += 1
    
    print(f"Found {len(classes)} NPN classes", file=__import__('sys').stderr)
    return classes

def main():
    print("// Auto-generated NPN table for 4-input functions.", file=__import__('sys').stderr)
    print("// Generated by gen_npn_table.py. DO NOT EDIT.", file=__import__('sys').stderr)
    print(file=__import__('sys').stderr)
    
    classes = count_classes()
    
    # Output Rust code
    print("use super::NpnTableEntry;")
    print()
    print("pub const NPN_TABLE_FULL: &[NpnTableEntry] = &[")
    for canon in sorted(classes.keys()):
        count, example = classes[canon]
        print(f"    NpnTableEntry {{")
        print(f"        canonical_tt: 0x{canon:04X},")
        print(f"        description: \"npn_class_{canon:04X}\",")
        print(f"        and_count: 0, // TODO: compute optimal via exhaustive search")
        print(f"    }}, // {count} functions, e.g. 0x{example:04X}")
    print("];")
    print(f"// Total: {len(classes)} classes", file=__import__('sys').stderr)

if __name__ == "__main__":
    main()
