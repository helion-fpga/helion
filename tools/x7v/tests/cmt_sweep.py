"""Build x7v/cmt_tables.json from Vivado bitstreams of the CMT sweep designs.

Usage: python3 tests/cmt_sweep.py <vivado out dir> [--write] [--rust PATH]

`--write` updates x7v/cmt_tables.json; `--rust PATH` writes the same measured
words as a Rust table for Helion's emitter (crates/helion-xilinx7/src/cmt_tables.rs).

The sweep (generated by `tests/cmt_sweep_gen.py`, built with Vivado 2017.3 for
xc7z020clg484-1) has one design per (BANDWIDTH, group of four feedback
multipliers): four MMCME2_ADV and four PLLE2_ADV, D = 1, each multiplier's
input clock chosen so the VCO is legal. The CMT's own bits say which
multiplier it has (CLKFBOUT counter), so placement does not matter. For each
(primitive, BANDWIDTH, M) this records the lock and loop-filter words
(mmcm.STATIC); every repeat must agree, or the script fails. POWER_REG is
recorded per primitive as the set of values seen, with the outputs in use,
from every design in the directory.
"""
from __future__ import annotations

import glob
import json
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from x7v import bit, decode, mmcm  # noqa: E402
from x7v.db import Db  # noqa: E402


def main(argv):
    root = argv[0]
    db = Db.for_part("xc7z020clg484-1")
    tables: dict = {}
    power: dict = {}
    seen_power: list = []
    bad = 0
    for path in sorted(glob.glob(os.path.join(root, "*", "*.bit"))):
        name = os.path.basename(os.path.dirname(path))
        m = re.match(r"sweep_(optimized|high|low)_\d+$", name)
        dec = decode.decode(db, bit.parse(path, db.part).frames)
        for tile, c in sorted(mmcm.tile_cmts(dec).items()):
            used = [o.name for o in c.outputs() if o.enabled]
            power.setdefault(c.kind, set()).add(c.power)
            seen_power.append((name, tile, c.kind, c.power, used))
            if not m:
                continue
            bw = m.group(1).upper()
            row = tables.setdefault(c.kind, {}).setdefault(bw, {})
            prev = row.get(str(c.m))
            if prev is not None and prev != c.static:
                print(f"CONFLICT {c.kind} {bw} M={c.m}: {prev} vs {c.static} ({name} {tile})")
                bad += 1
            row[str(c.m)] = c.static
    for kind, bws in sorted(tables.items()):
        for bw, rows in sorted(bws.items()):
            ms = sorted(int(k) for k in rows)
            missing = sorted(set(range(2, 65)) - set(ms))
            print(f"{kind} {bw}: {len(ms)} multipliers, missing {missing}")
        same = [m for m in bws.get("OPTIMIZED", {}) if bws["OPTIMIZED"][m] == bws.get("HIGH", {}).get(m)]
        print(f"{kind}: OPTIMIZED == HIGH for {len(same)} multipliers")
    for p in seen_power:
        if p[3] not in (0, 0x100) or p[4]:
            print("POWER_REG", f"{p[3]:#06x}", p[0], p[1], p[2], ",".join(p[4]))
    tables["POWER_REG"] = {k: sorted(v) for k, v in power.items()}
    if "--write" in argv and not bad:
        with open(mmcm.TABLES_PATH, "w") as f:
            json.dump(tables, f, indent=1, sort_keys=True)
            f.write("\n")
        print("wrote", mmcm.TABLES_PATH)
    if "--rust" in argv and not bad:
        write_rust(argv[argv.index("--rust") + 1], tables)
    return 1 if bad else 0


def write_rust(path: str, tables: dict) -> None:
    keys = list(mmcm.STATIC)
    out = ["//! Lock and loop-filter words Vivado 2017.3 writes for each MMCM/PLL",
           "//! feedback multiplier, measured from its bitstreams of the CMT sweep",
           "//! designs (generated by tools/x7v/tests/cmt_sweep.py; do not edit).",
           f"//! Columns: {', '.join(keys)}. BANDWIDTH HIGH equals OPTIMIZED.", ""]
    for kind, rust in (("MMCME2_ADV", "MMCM"), ("PLLE2_ADV", "PLL")):
        for bw in ("OPTIMIZED", "LOW"):
            rows = tables[kind][bw]
            out.append(f"pub const {rust}_{bw}: [(u32, [u64; {len(keys)}]); {len(rows)}] = [")
            for m in sorted(rows, key=int):
                out.append(f"    ({m}, [{', '.join(hex(rows[m][k]) for k in keys)}]),")
            out.append("];")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
